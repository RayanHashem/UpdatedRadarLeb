/* FNV-1a: turns the seed text into a 32-bit number. */
function hashSeed(text: string): number {
    let h = 2166136261;
    for (let i = 0; i < text.length; i++) {
        h ^= text.charCodeAt(i);
        h = Math.imul(h, 16777619);
    }
    return h >>> 0;
}

/* mulberry32: small seeded random generator (same seed → same numbers). */
function seededRandom(seed: number): () => number {
    let a = seed;
    return () => {
        a = (a + 0x6d2b79f5) | 0;
        let t = Math.imul(a ^ (a >>> 15), 1 | a);
        t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}

/**
 * The order in which a player's antennas light up the regions for one
 * prize: a shuffle seeded by player + prize, so it looks random but never
 * changes on reload.
 */
export function regionOrder(userId: number | string | null | undefined, gameId: number | string): RegionKey[] {
    const random = seededRandom(hashSeed(`radarleb:${userId ?? 'guest'}:${gameId}`));
    const keys = REGIONS.map((r) => r.key);
    for (let i = keys.length - 1; i > 0; i--) {
        const j = Math.floor(random() * (i + 1));
        [keys[i], keys[j]] = [keys[j], keys[i]];
    }
    return keys;
}
